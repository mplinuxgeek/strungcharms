"""Build bambu-profiles.js for StrungCharms from Bambu Studio's system presets.

Usage: python3 tools/build_bambu_profiles.py <BambuStudio profiles dir> bambu-profiles.js [version]
Flatpak profiles dir: $(flatpak info --show-location com.bambulab.BambuStudio)/files/share/BambuStudio/profiles
Each preset is flattened (inherits + include templates resolved) so the exported 3MF carries the full system
preset values: Bambu Studio fills any key missing from a project with its built-in defaults, not the preset's.
"""
import json, os, sys
B = sys.argv[1]; OUT = sys.argv[2]; VERSION = sys.argv[3] if len(sys.argv) > 3 else '02.09.01.70'
def load(kind):
    out = {}
    for f in os.listdir(os.path.join(B, 'BBL', kind)):
        if f.endswith('.json'):
            d = json.load(open(os.path.join(B, 'BBL', kind, f)))
            if 'name' in d: out[d['name']] = d
    return out
C = {k: load(k) for k in ('machine', 'process', 'filament')}
META = {'type', 'name', 'inherits', 'from', 'setting_id', 'instantiation', 'description', 'compatible_printers', 'compatible_printers_condition',
        'compatible_prints', 'compatible_prints_condition', 'filament_id', 'renamed_from', 'version', 'is_custom_defined', 'include'}
def chain(kind, name):
    seq = []
    while name:
        d = C[kind][name]; seq.append(d); name = d.get('inherits')
    out = {}
    for d in reversed(seq):
        for inc in d.get('include', []):
            out.update({k: v for k, v in C[kind][inc].items() if k not in META})
        out.update(d)
    out.pop('include', None)
    return out
SET = {
 'a1mini': ('Bambu Lab A1 mini 0.4 nozzle', '0.20mm Standard @BBL A1M', 'Bambu PLA Basic @BBL A1M'),
 'a1':     ('Bambu Lab A1 0.4 nozzle', '0.20mm Standard @BBL A1', 'Bambu PLA Basic @BBL A1'),
 'p1s':    ('Bambu Lab P1S 0.4 nozzle', '0.20mm Standard @BBL X1C', 'Bambu PLA Basic @BBL P1S 0.4 nozzle'),
 'x1c':    ('Bambu Lab X1 Carbon 0.4 nozzle', '0.20mm Standard @BBL X1C', 'Bambu PLA Basic @BBL X1C'),
 'p2s':    ('Bambu Lab P2S 0.4 nozzle', '0.20mm Standard @BBL P2S', 'Bambu PLA Basic @BBL P2S'),
 'h2s':    ('Bambu Lab H2S 0.4 nozzle', '0.20mm Standard @BBL H2S', 'Bambu PLA Basic @BBL H2S'),
}
P = {}
for key, (mn, pn, fn) in SET.items():
    m, p, f = chain('machine', mn), chain('process', pn), chain('filament', fn)
    cfg = {k: v for k, v in {**m, **p}.items() if k not in META}
    fil = {k: v for k, v in f.items() if k not in META}
    clash = set(cfg) & set(fil)
    cfg = {k: v for k, v in cfg.items() if k not in fil}
    cfg.update({'printer_settings_id': mn, 'print_settings_id': pn, 'print_compatible_printers': p.get('compatible_printers', []),
                'default_bed_type_': m.get('default_bed_type', 'Textured PEI Plate')})
    P[key] = {'cfg': cfg, 'fil': fil, 'fname': fn, 'fid': f.get('filament_id', ''), 'clash': sorted(clash)}
# dedupe
def dedupe(part):
    keys = set().union(*(P[k][part] for k in P))
    base = {}
    for kk in keys:
        vals = {json.dumps(P[k][part].get(kk, '\0missing')) for k in P}
        if len(vals) == 1: base[kk] = P[next(iter(P))][part][kk]
    return base
bc, bf = dedupe('cfg'), dedupe('fil')
out = {'version': VERSION, 'base': {'cfg': bc, 'fil': bf},
       'printers': {k: {'cfg': {kk: v for kk, v in P[k]['cfg'].items() if kk not in bc}, 'fil': {kk: v for kk, v in P[k]['fil'].items() if kk not in bf},
                        'fname': P[k]['fname'], 'fid': P[k]['fid']} for k in P}}
s = json.dumps(out, separators=(',', ':'), ensure_ascii=False)
open(OUT, 'w').write('// generated by tools/build_bambu_profiles.py from Bambu Studio system presets - do not edit\nwindow.BBL_PROFILES = ' + s + ';\n')
print('bytes', len(s), 'base', len(bc), len(bf))
